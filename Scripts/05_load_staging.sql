USE ModernCRM;
GO
IF SCHEMA_ID('stg') IS NULL EXEC('CREATE SCHEMA stg');
GO
IF OBJECT_ID('stg.CUST_MASTER', 'U') IS NOT NULL DROP TABLE stg.CUST_MASTER;
IF OBJECT_ID('stg.ORDER_HDR', 'U') IS NOT NULL DROP TABLE stg.ORDER_HDR;
GO
SELECT IDENTITY(INT, 1, 1) AS StgRowID, *
INTO stg.CUST_MASTER
FROM LegacyCRM.dbo.CUST_MASTER;
SELECT IDENTITY(INT, 1, 1) AS StgRowID, *
INTO stg.ORDER_HDR
FROM LegacyCRM.dbo.ORDER_HDR;
GO
SELECT 'CUST_MASTER' AS TableName,
       (SELECT COUNT(*) FROM LegacyCRM.dbo.CUST_MASTER) AS SourceRows,
       (SELECT COUNT(*) FROM stg.CUST_MASTER) AS StagingRows
UNION ALL
SELECT 'ORDER_HDR',
       (SELECT COUNT(*) FROM LegacyCRM.dbo.ORDER_HDR),
       (SELECT COUNT(*) FROM stg.ORDER_HDR);